package com.mobisec.in.contentservice.config;

import io.minio.MinioClient;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

@Configuration
public class MinioConfig {

    @Value("${minio.endpoint}")
    private String endpoint;

    @Value("${minio.access-key}")
    private String accessKey;

    @Value("${minio.secret-key}")
    private String secretKey;

    /**
     * Sync MinioClient — used for presigned URL generation, statObject, deleteObject.
     * Thread-safe singleton.
     *
     * MinioMultipartClient (multipart lifecycle) is a @Component and
     * is wired by Spring automatically — no @Bean method needed here.
     */
    @Bean
    public MinioClient minioClient() {
        return MinioClient.builder()
                .endpoint(endpoint)
                .credentials(accessKey, secretKey)
                .build();
    }
}